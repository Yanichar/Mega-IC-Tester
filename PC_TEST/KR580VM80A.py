#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
KR580VM80A.py — functional tester for the KR580VM80A microprocessor (DIP-40)
based on the Mega-IC-Tester (PC mode, SIMPL).

Idea
====
The tester has no memory of its own: the host PC **is the bus itself**. The
ZIF-40 pins are controlled through the Arduino one at a time, so the PC acts
as the clock generator, the memory and the I/O devices, while the KR580VM80A
executes real programs.

Differences from the Z80 that had to be taken into account
=======================================
1. TWO non-overlapping clock inputs: PHI1 (pin 22) and PHI2 (pin 15).
   The processor advances state on PHI2, so a single CLK "tick" as on
   the Z80 does not work — one cycle is a pair of pulses PHI1 -> PHI2.
2. A single supply rail. The tester cannot provide -5 V and +12 V, so
   the officially documented non-standard mode is used:

       pin 28 (+12 V) -> +5 V      pin 11 (-5 V) -> 0 V (common)

   In this mode the processor is operational but requires a **fast**
   clock: the i8080 is built on dynamic logic, and at a clock of a few
   hertz the internal nodes lose their state. Verified on hardware: with
   a "slow" manual clock (tens of milliseconds per cycle) the processor
   walks the addresses correctly but reads every instruction as 0x00 (NOP)
   and outputs a status word of 0x00 in T1. At a clock of tens of
   kilohertz the same part executes programs correctly, and the status
   word reads as 0xA0/0xA2 (M1+MEMR).

Clock and synchronization
====================
The clock is generated by the firmware: one SIMPL command starts a burst
of cycles (`N{65h3u65l3u50h3u50l3u}`). The frequency is capped from above
by the requirement "no more than 100 kHz" (MAX_CLOCK_HZ) — it is checked
in the constructor, in the CLI and measured at startup.

Communication with the processor is done "one machine cycle at a time" and
relies on the READY input (READY, pin 23) — exactly as described in the
Intel 8080A datasheet ("READY can also be used to single step the CPU"):

    * with READY=0 the processor enters the wait state (two or more
      TW cycles) and **holds the bus unchanged** for as long as needed
      (note 10: READY must be stable in T2 or TW);
    * the host reads the address and the control lines (DBIN/WR) and drives
      the required byte;
    * a short burst "READY=1 for one cycle, then READY=0 plus another ten
      cycles" lets the processor pass through exactly one transaction and
      puts it back into the wait state.

The result is one transaction per round-trip to the Arduino (~10 ms), but
the clock inside the burst runs at tens of kilohertz. The processor
tolerates the pauses between bursts calmly (verified on hardware: programs
made of MVI/LXI/ALU/PCHL run to completion).

What the datasheet requires and how it is implemented
=======================================
Intel 8080A, Table 1 and A.C. Characteristics:

  * "during the first clock cycle of each machine cycle the 8080A outputs
    a status word on the data bus" — in cycle T1 the processor drives the
    data bus, so our driver must already be released by that moment;
  * note 1: "Data input should be enabled with DBIN status. No bus
    conflict can then occur and data hold time is assured" — the byte may
    be driven only while DBIN is active;
  * note 9: "Data in must be stable for this period during DBIN T3.
    Both tOS1 and tOS2 must be satisfied" — the data must be stable with
    respect to both the PHI1 edge (tOS1 = 30 ns) and the PHI2 edge
    (tOS2 = 150 ns) during DBIN;
  * note 10: READY must be stable in T2/TW.

(Source: Intel "8080A/8080A-1/8080A-2 8-Bit N-Channel Microprocessor",
Table 1 "Pin Description" and the A.C. Characteristics section, notes 1, 9,
10; Fig. 2 "Pin Configuration" — the pinout was cross-checked.)

Hence the order in _advance(): the byte is driven inside the same SIMPL
command, immediately before the enabling cycle, and is held for one more
cycle — until the end of DBIN, after which the data bus is released so as
not to interfere with the processor driving the status word in T1 of the
next machine cycle. Verified on hardware: if the bus is released earlier or
the byte is driven by a separate command long before the cycle, the
processor reads 0x00.

About the frequency: per the datasheet the clock period is
tCY = 0.48..2.0 us, that is, formally 0.5..2 MHz is required. The SIMPL
interpreter does not deliver that — the burst runs at tens of kilohertz,
which is outside the A.C. characteristics window, but on a real KR580VM80A
part everything works reliably (the full test suite passes repeatably). The
"no more than 100 kHz" ceiling set by the customer is respected.

One transaction
=======================
    1) read the bus (address + DBIN/WR) — the processor is waiting;
    2) if DBIN=1 — drive a byte from "memory" (inside the burst, see above),
       if WR=0 — release the bus (the processor drives it);
    3) with the burst "READY=1 for one cycle, then READY=0" pass one
       transaction.

Data bus safety
========================
The D0..D7 bus is bidirectional, so a byte is driven ONLY when DBIN=1 and
there is no write. When a write cycle is detected the run stops immediately
(all tests in this file are built on "reading" programs: NOP, MVI, LXI,
MOV, ALU, PCHL — no write cycles occur).

Detecting opcode fetches
=================================
The M1 flag (bit D5 of the status word) is driven in T1, while the
transaction happens in the wait state (T2/TW), so fetches are identified by
our own decoder of 8080 instruction structure: we drive the bytes
ourselves, so we know how many operand bytes follow each opcode. The
algorithm:

    * an open fetch (we expect an opcode) — the address is recorded in the
      fetch list;
    * the length of the current instruction is known from the INSTR_LEN
      table — that many following reads are treated as operands;
    * the DATA_READS table adds one more machine read cycle for
      instructions that read a byte at the address held in a register pair
      (LDA/LHLD/LDAX, MOV r,M, INR M/DCR M, ALU with the M operand) —
      otherwise such an address (for example 0100h for LDA) could be
      mistaken for a new instruction.

RESET
=====
The RESET input (pin 12) on the i8080/KR580VM80A is active HIGH (on the
i8085 it is the opposite, RESET IN is active low). Reset is held for 8
cycles, then released simultaneously with READY=0, so the very first
machine cycle stops in T2 at address 0000h — exactly where the program
starts.

How the result is verified
=========================
The internal registers are not visible from outside, so the trick of
"putting the result on the address bus" is used:

    MVI  H, 02h
    MOV  L, A
    PCHL              ; the next fetch is at address 0200h + A

So by looking at which address the CPU fetched the next byte from, one can
read the contents of a register. This gives a genuine check of the ALU, the
registers, the flags, the conditional jumps and the whole 16-bit address
bus.

Existing project files are not modified: the module only imports
base_test / arduino_to_pins / simpl_macros.

Usage
======
    python KR580VM80A.py                 # the whole test suite
    python KR580VM80A.py --port COM11    # specify the port explicitly
    python KR580VM80A.py --monitor       # show the bus state
    python KR580VM80A.py --test alu      # run a single test
    python KR580VM80A.py --selftest      # checks without hardware
    python KR580VM80A.py --clock 50000   # frequency ceiling, Hz (<= 100000)
"""

