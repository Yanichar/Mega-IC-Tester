MAX_CLOCK_HZ = 100_000

# Smallest duration of one half-period (PHI1 and PHI2) in a burst, us.
# The firmware performs delays via delayMicroseconds, so 1 .. 2 us
# at 16 MHz gives a period of ~8-15 us (70-120 kHz), which already hits
# the ceiling, so the lower bound is derived from the ceiling.
MIN_HALF_US = 2

# How many cycles to hold READY=0 after the enabling cycle so that the
# processor has time to reach the next T2 and stop. The margin is more
# than sufficient.
WAIT_CYCLES = 12

# How many cycles to apply after reset is released so that the processor
# reaches the first T2 and enters the wait state.
START_CYCLES = 6

# ---------------------------------------------------------------------------
# KR580VM80A pinout (DIP-40). The order of the elements = the chip pin
# number, i.e. the position in the ZIF-40. The value = the Arduino pin from
# arduino_to_pins.pin40.
# ---------------------------------------------------------------------------
KR580VM80A_SIGNALS = [
    "A10",                                  # 1
    "GND",                                  # 2   common rail (0 V)
    "D4", "D5", "D6", "D7", "D3", "D2",     # 3..8
    "D1", "D0",                             # 9..10
    "VBB",                                  # 11  -5 V -> 0 V for us
    "RESET",                                # 12  active HIGH
    "HOLD",                                 # 13
    "INT",                                  # 14  active high
    "CLK2",                                 # 15  PHI2
    "INTE",                                 # 16
    "DBIN",                                 # 17  read (active high)
    "WR",                                   # 18  write (active low)
    "SYNC",                                 # 19
    "VCC",                                  # 20  +5 V
    "HLDA",                                 # 21
    "CLK1",                                 # 22  PHI1
    "READY",                                # 23  1 = ready (READY)
    "WAIT",                                 # 24
    "A0", "A1", "A2",                       # 25..27
    "VDD",                                  # 28  +12 V -> +5 V for us
    "A3", "A4", "A5", "A6", "A7", "A8",     # 29..34
    "A9",                                   # 35
    "A15", "A12", "A13", "A14", "A11",      # 36..40
]

