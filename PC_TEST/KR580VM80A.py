TESTS = {
    "nop": test_nop_walk,
    "decode": test_instruction_lengths,
    "flow": test_control_flow,
    "alu": test_alu_8bit,
    "addr": test_address_bus,
    "data": test_data_bus,
    "alu16": test_alu_16bit,
}

ORDER = ["nop", "decode", "flow", "alu", "addr", "data", "alu16"]


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="KR580VM80A functional tester (DIP-40) "
                    "on the Mega-IC-Tester"
    )
    parser.add_argument("--port", default=DEFAULT_PORT,
                        help=f"Arduino COM port (default {DEFAULT_PORT})")
    parser.add_argument("--clock", type=int, default=MAX_CLOCK_HZ,
                        help="clock frequency ceiling, Hz "
                             f"(no more than {MAX_CLOCK_HZ})")
    parser.add_argument("--monitor", action="store_true",
                        help="only print the bus state and exit")
    parser.add_argument("--selftest", action="store_true",
                        help="checks without hardware (pinout, programs)")
    parser.add_argument("--test", action="append", choices=ORDER,
                        help="run only the specified test "
                             "(may be given several times)")
    args = parser.parse_args(argv)

    if args.clock > MAX_CLOCK_HZ:
        parser.error(f"frequency ceiling {MAX_CLOCK_HZ} Hz: "
                     "cannot be set higher (the 'no more than 100 kHz' requirement)")
    if args.clock <= 0:
        parser.error("frequency must be positive")

    if args.selftest:
        return selftest()

    t = TestKR580VM80A(port=args.port, clock_hz=args.clock)
    failed = []
    try:
        if args.monitor:
            test_monitor(t)
            return 0

        selected = args.test or ORDER
        for name in selected:
            fn = TESTS[name]
            try:
                fn(t)
            except AssertionError as exc:
                failed.append(name)
                print(f"    FAILED [{name}]: {exc}")
            except IOError as exc:
                # Link lost — there is no point in continuing
                print(f"    LINK ERROR [{name}]: {exc}")
                failed.append(name)
                break
    finally:
        try:
            t.close()
        except Exception:
            pass

    print("\n" + "=" * 62)
    if failed:
        print("FAILED:", ", ".join(failed))
        return 1
    print("ALL TESTS PASSED")
    return 0


if __name__ == "__main__":
    sys.exit(main())
