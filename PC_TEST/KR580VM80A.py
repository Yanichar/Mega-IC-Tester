    #   0000  MVI A,val
    #   0002  <flag setup>
    #   0003  Jcc 0009h
    #   0006  MVI A,05h
    #   0008  NOP
    #   0009  MVI H,02h
    #   000B  MOV L,A
    #   000C  PCHL
